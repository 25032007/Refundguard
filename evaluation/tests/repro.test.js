/**
 * Phase 3: published-output reproducibility tests.
 *
 * Verifies that `npm run eval:report` (the docs-writing path) is
 * byte-reproducible:
 *  1. A re-run of reportPhase() produces byte-identical files under docs/
 *     (EVALUATION.md + docs/results/*) — no timestamps, no machine paths.
 *  2. Files use LF line endings regardless of host OS.
 *  3. Committed outputs contain no absolute machine paths (drive letters,
 *     user directory) and no wall-clock timestamp fields (frozenAt /
 *     generatedAt / evaluationTimestamp).
 *  4. Any perRingTablePath stored inside the machine-readable final result is
 *     repo-relative with forward slashes.
 *
 * Gated on the phase-3 caches and committed docs; skipped otherwise.
 */

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const report = require('../report');
const seeds = require('../seeds');

const DOCS_RESULTS = report.DOCS_RESULTS;
const EVALUATION_MD = report.EVALUATION_MD;
const FINAL_RESULT = path.join(DOCS_RESULTS, 'final-eval-result.json');

const gates = [
  report.CACHE_PATH.frozenConfig,
  report.CACHE_PATH.thresholds,
  report.CACHE_PATH.unseen,
  path.join(DOCS_RESULTS, 'ring-escalation.json'),
  path.join(DOCS_RESULTS, 'eval-summary.json'),
  path.join(DOCS_RESULTS, 'config.json'),
  path.join(DOCS_RESULTS, 'leadtime.json'),
  path.join(DOCS_RESULTS, `leadtime-per-ring-${seeds.HELD_OUT_SEEDS[0]}.json`),
  EVALUATION_MD
];
const SKIP_REASON = !gates.every(p => fs.existsSync(p))
  ? 'Phase 3 caches/committed docs not present — run `npm run eval:report` first'
  : false;

function sha256(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex');
}

function snapshotDocs() {
  const out = {};
  out['docs/EVALUATION.md'] = sha256(fs.readFileSync(EVALUATION_MD));
  for (const name of fs.readdirSync(DOCS_RESULTS).sort()) {
    const file = path.join(DOCS_RESULTS, name);
    if (fs.statSync(file).isFile()) out[`docs/results/${name}`] = sha256(fs.readFileSync(file));
  }
  return out;
}

test('Phase 3: eval:report output is byte-reproducible with no machine paths or timestamps', { skip: SKIP_REASON }, async (t) => {
  const before = snapshotDocs();

  await t.test('first reportPhase run matches the committed docs bytes', async () => {
    await report.reportPhase();
    const after = snapshotDocs();
    assert.deepStrictEqual(after, before, 'docs must be regenerated byte-identically');
  });

  await t.test('second reportPhase run is byte-identical to the first', async () => {
    await report.reportPhase();
    const after = snapshotDocs();
    assert.deepStrictEqual(after, before, 'a repeated run must not change docs bytes');
  });

  await t.test('generated docs use LF line endings and contain no wall-clock timestamps', () => {
    for (const [rel, hash] of Object.entries(snapshotDocs())) {
      const content = fs.readFileSync(path.join(report.REPO_ROOT, rel), 'utf8');
      assert.ok(!content.includes('\r'), `${rel} must not contain CR (LF-only)`);
      assert.ok(!content.includes('frozenAt'), `${rel} must not contain frozenAt`);
      assert.ok(!content.includes('generatedAt'), `${rel} must not contain generatedAt`);
      assert.ok(!content.includes('evaluationTimestamp'), `${rel} must not contain evaluationTimestamp`);
      assert.ok(!content.includes('Generated at:'), `${rel} must not contain a Generated-at header`);
    }
  });

  await t.test('generated docs contain no machine-specific absolute paths', () => {
    const all = Object.entries(snapshotDocs())
      .map(([rel]) => fs.readFileSync(path.join(report.REPO_ROOT, rel), 'utf8'))
      .join('\n');
    assert.ok(!/^[A-Za-z]:[\\/]/m.test(all), 'no drive-letter absolute paths');
    assert.ok(!/Users[\\/]/i.test(all), 'no user-directory paths');
    assert.ok(!/Refundguard_Razorpay_AI_Buildathon/i.test(all), 'no repo machine path');
  });

  await t.test('final-eval-result.json stores repo-relative per-ring paths', () => {
    assert.ok(fs.existsSync(FINAL_RESULT), 'final-eval-result.json must be committed');
    const final = JSON.parse(fs.readFileSync(FINAL_RESULT, 'utf8'));
    for (const seed of final.heldOutResults.leadTime.perSeed) {
      assert.ok(
        /^docs\/results\/leadtime-per-ring-\d+\.json$/.test(seed.perRingTablePath),
        `perRingTablePath must be repo-relative: ${seed.perRingTablePath}`
      );
      assert.ok(!seed.perRingTablePath.includes('\\'), 'perRingTablePath must use forward slashes');
    }
  });
});